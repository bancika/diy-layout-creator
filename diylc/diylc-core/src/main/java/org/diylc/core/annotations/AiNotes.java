package org.diylc.core.annotations;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Container that lets {@link AiNote} be repeated on a class. Never written by hand: the compiler
 * creates it when a class carries more than one {@link AiNote}.
 *
 * @author Branislav Stojkovic
 */
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
public @interface AiNotes {

  AiNote[] value();
}
