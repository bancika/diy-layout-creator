  private DotMatrixFont() {}

  /** Whether the glyph for a character lights the dot at the given row and column of its cell. */
  public static boolean isDotLit(char c, int row, int column) {
    if (row < 0 || row >= GLYPH_HEIGHT || column < 0 || column >= GLYPH_WIDTH) {
      return false;
    }
    char glyph = c < FIRST_CHAR || c > LAST_CHAR ? FALLBACK_CHAR : c;
    return (GLYPH_COLUMNS[(glyph - FIRST_CHAR) * GLYPH_WIDTH + column] >> row & 1) != 0;
  }
